import {z} from 'zod/v4';
import {Id,DateTime,Plan,Brief,RunStatus,RunTrigger,Phase,FailCode} from './common';
import {FeedItem,Origin} from './vista';
export const User=z.object({id:Id,name:z.string(),email:z.email(),avatarUrl:z.url().nullable()}).strict();
export const UsageCount=z.object({used:z.number().int().nonnegative(),max:z.number().int().positive()}).strict();
export const ModelSummary=z.object({connected:z.boolean(),provider:z.literal('openrouter').optional(),modelId:z.string().optional(),keyHint:z.string().optional()}).strict();
export const MeResponse=z.object({user:User,workspaceId:Id,plan:Plan,usage:z.object({channels:UsageCount,runsToday:UsageCount}).strict(),model:ModelSummary,nextUpdateAt:DateTime.nullable()}).strict();
export const Schedule=z.object({intervalMin:z.number().int().positive().nullable(),enabled:z.boolean(),nextRunAt:DateTime.nullable(),lastRunAt:DateTime.nullable()}).strict();
export const ChannelOrigin=z.object({channelId:Id,workspaceId:Id}).strict();
export const Channel=z.object({id:Id,title:z.string(),brief:Brief,createdAt:DateTime,latestVistaId:Id.nullable().optional(),latestPosterUrl:z.url().nullable().optional(),schedule:Schedule,origin:ChannelOrigin.nullable()}).strict();
export const ChannelsResponse=z.object({items:z.array(Channel)}).strict();
export const CreateChannel=z.object({brief:Brief,intervalMin:z.number().int().positive().optional()}).strict();
export const CreateChannelResponse=z.object({channelId:Id,runId:Id}).strict();
export const UpdateChannel=z.object({intervalMin:z.number().int().positive().nullable().optional(),enabled:z.boolean().optional(),title:z.string().trim().min(1).max(80).optional()}).strict();
export const CreateRun=z.object({channelId:Id,prompt:Brief}).strict();
export const CreateRunResponse=z.object({runId:Id}).strict();
export const RunResponse=z.object({status:RunStatus,phase:Phase,trigger:RunTrigger.optional(),vistaId:Id.optional(),error:FailCode.optional()}).strict();
export const FeedResponse=z.object({items:z.array(FeedItem),nextCursor:z.string().nullable()}).strict();
export const OAuthCallback=z.object({code:z.string().min(1),state:z.string().min(16)});
// Dev-only login used for local verification with several independent accounts. Disabled unless AUTH_DEV_ACCOUNTS is set.
export const DevLogin=z.object({email:z.email(),name:z.string().trim().min(1).max(80)}).strict();
export const RuntimeResponse=z.object({runtimeId:Id,status:z.enum(['idle','running']),activeRuns:z.number().int().nonnegative(),nextWakeAt:DateTime.nullable()}).strict();
export const AskRequest=z.object({vistaId:Id,question:z.string().trim().min(1).max(500)}).strict();
export const AskResponse=z.object({answer:z.string().min(1).max(4000),modelId:z.string()}).strict();
export type ChannelData=z.infer<typeof Channel>;
export type FeedItemData=z.infer<typeof FeedItem>;
export { Origin };
// Inferred TypeScript types (same names as the schemas; value and type namespaces are separate).
export type User=z.infer<typeof User>;
export type UsageCount=z.infer<typeof UsageCount>;
export type ModelSummary=z.infer<typeof ModelSummary>;
export type MeResponse=z.infer<typeof MeResponse>;
export type Schedule=z.infer<typeof Schedule>;
export type ChannelOrigin=z.infer<typeof ChannelOrigin>;
export type Channel=z.infer<typeof Channel>;
export type ChannelsResponse=z.infer<typeof ChannelsResponse>;
export type CreateChannel=z.infer<typeof CreateChannel>;
export type CreateChannelResponse=z.infer<typeof CreateChannelResponse>;
export type UpdateChannel=z.infer<typeof UpdateChannel>;
export type CreateRun=z.infer<typeof CreateRun>;
export type CreateRunResponse=z.infer<typeof CreateRunResponse>;
export type RunResponse=z.infer<typeof RunResponse>;
export type FeedResponse=z.infer<typeof FeedResponse>;
export type OAuthCallback=z.infer<typeof OAuthCallback>;
export type DevLogin=z.infer<typeof DevLogin>;
export type RuntimeResponse=z.infer<typeof RuntimeResponse>;
export type AskRequest=z.infer<typeof AskRequest>;
export type AskResponse=z.infer<typeof AskResponse>;
